#!/usr/bin/env bash
# PiDash installer. Run from inside the pidash folder:   bash install.sh
# Re-run it any time you change apps.yaml.
set -euo pipefail

DIR="$(cd "$(dirname "$0")" && pwd)"
USER_NAME="$(whoami)"
SYSTEMCTL="$(command -v systemctl)"
cd "$DIR"

echo "==> Python environment"
sudo apt-get install -y -qq python3-venv > /dev/null
[ -d .venv ] || python3 -m venv .venv
.venv/bin/pip install -q --upgrade pip
.venv/bin/pip install -q -r requirements.txt

echo "==> Letting the dashboard start/stop only the services in apps.yaml"
TMP="$(mktemp)"
.venv/bin/python - "$USER_NAME" "$SYSTEMCTL" > "$TMP" <<'EOF'
import re, sys
from pidash import load_config
user, systemctl = sys.argv[1], sys.argv[2]
ok = re.compile(r"^[A-Za-z0-9@._-]+\.(service|timer)$")
lines = ["# Generated by PiDash install.sh from apps.yaml. Do not edit by hand."]
for app in load_config()["apps"]:
    for u in app["units"]:
        if not ok.match(u):
            sys.exit(f"Bad unit name in apps.yaml: {u!r}")
        for action in ("start", "stop", "restart", "enable", "disable"):
            lines.append(f"{user} ALL=(root) NOPASSWD: {systemctl} {action} {u}")
    for u in app["measure"]:
        if not ok.match(u):
            sys.exit(f"Bad unit name in apps.yaml: {u!r}")
        lines.append(f"{user} ALL=(root) NOPASSWD: {systemctl} stop {u}")
print("\n".join(lines))
EOF
if sudo visudo -cf "$TMP" > /dev/null; then
  sudo install -m 0440 -o root -g root "$TMP" /etc/sudoers.d/pidash
else
  echo "!! Generated permissions file failed validation; not installed."; rm -f "$TMP"; exit 1
fi
rm -f "$TMP"

echo "==> Dashboard service"
sed -e "s|__DIR__|$DIR|g" -e "s|__USER__|$USER_NAME|g" systemd/pidash.service | sudo tee /etc/systemd/system/pidash.service > /dev/null
sudo systemctl daemon-reload
sudo systemctl enable pidash.service > /dev/null
sudo systemctl restart pidash.service

PORT="$(.venv/bin/python -c 'from pidash import load_config; print(load_config().get("web",{}).get("port",8000))')"
echo
echo "Done! Open  http://$(hostname).local:$PORT  on any device on your Wi-Fi."
